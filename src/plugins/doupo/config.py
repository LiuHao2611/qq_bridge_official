#: 丹药功效 → 短标签（唯一源：炼药纯文本 / 卡片共用，杜绝两处口径分叉）。
#: 用户 2026-11-18「怎么没看到恢复斗气的丹药」——旧版只写 desc 文字，玩家认不出
#: 哪枚回斗气，必须在丹名前显式挂一枚 2~3 字短标签。
